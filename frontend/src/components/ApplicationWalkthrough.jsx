function wrap(index, count) {
  return (index + count) % count;
}

function StepImage({ step }) {
  return step.image
    ? <img src={step.image} alt={step.alt} loading="lazy" decoding="async" />
    : <span className="planned-preview">Planned workflow</span>;
}

export default function ApplicationWalkthrough() {
  const [applicationIndex, setApplicationIndex] = useState(0);
  const [stepIndex, setStepIndex] = useState(0);
  const tabs = useRef([]);
  const touchStart = useRef(null);
  const application = applications[applicationIndex];
  const { steps } = application;
  const step = steps[stepIndex];

  function selectApplication(index) {
    if (index === applicationIndex) return;
    setApplicationIndex(index);
    setStepIndex(0);
  }

  function handleTabKeys(event) {
    const directions = { ArrowLeft: -1, ArrowRight: 1 };
    let next;
    if (event.key === "Home") next = 0;
    else if (event.key === "End") next = applications.length - 1;
    else if (event.key in directions) next = wrap(applicationIndex + directions[event.key], applications.length);
    else return;
    event.preventDefault();
    selectApplication(next);
    tabs.current[next]?.focus();
  }

  function moveStep(direction) {
    setStepIndex((index) => wrap(index + direction, steps.length));
  }

  function handleTouchEnd(event) {
    const start = touchStart.current;
    touchStart.current = null;
    if (!start) return;
    const end = event.changedTouches[0];
    const dx = end.clientX - start.x;
    const dy = end.clientY - start.y;
    if (Math.abs(dx) >= 45 && Math.abs(dx) > Math.abs(dy)) moveStep(dx < 0 ? 1 : -1);
  }

  return (
    <section className="section applications-section" id="applications" tabIndex={-1} aria-labelledby="applications-title">
      <div className="wrap">
        <div className="section-heading">
          <p className="kicker">From shared intelligence to practical solutions</p>
          <h2 id="applications-title">One platform.<br /><em>Multiple possibilities.</em></h2>
        </div>
        <div className="application-tabs" role="tablist" aria-label="Choose an application" onKeyDown={handleTabKeys}>
          {applications.map(({ id, category, name, summary }, index) => (
            <button
              className="application-tab"
              key={id}
              id={`application-tab-${id}`}
              ref={(node) => { tabs.current[index] = node; }}
              type="button"
              role="tab"
              aria-selected={index === applicationIndex}
              aria-controls={`application-panel-${id}`}
              tabIndex={index === applicationIndex ? 0 : -1}
              onClick={() => selectApplication(index)}
            >
              <span className="kicker">{category}</span>
              <strong>{name}</strong>
              <small>{summary}</small>
            </button>
          ))}
        </div>

        {applications.map(({ id }, index) => (
          <div
            key={id}
            id={`application-panel-${id}`}
            role="tabpanel"
            aria-labelledby={`application-tab-${id}`}
            hidden={index !== applicationIndex}
          >
            {index === applicationIndex && (
              <>
                <div className="walkthrough-intro">
                  <h4>{application.title}</h4>
                  <p>{application.description}</p>
                </div>
                <div
                  className="walkthrough-deck"
                  onTouchStart={(event) => {
                    const { clientX, clientY } = event.touches[0];
                    touchStart.current = { x: clientX, y: clientY };
                  }}
                  onTouchEnd={handleTouchEnd}
                  onTouchCancel={() => { touchStart.current = null; }}
                >
                  {[-1, 1].map((direction) => {
                    const neighbor = steps[wrap(stepIndex + direction, steps.length)];
                    return (
                      <button
                        key={direction}
                        type="button"
                        className={`walkthrough-card preview-card ${direction < 0 ? "previous-card" : "next-card"}`}
                        aria-label={`Go to ${direction < 0 ? "previous" : "next"} step: ${neighbor.title}`}
                        onClick={() => moveStep(direction)}
                      >
                        <span className="walkthrough-image" aria-hidden="true">
                          <StepImage step={neighbor} />
                        </span>
                        <span>{neighbor.title}</span>
                      </button>
                    );
                  })}
                  <article className="walkthrough-card current-card" aria-live="polite" aria-atomic="true">
                    <div className="walkthrough-image"><StepImage step={step} /></div>
                    <div className="step-copy">
                      <p className="kicker">Step {stepIndex + 1} of {steps.length}</p>
                      <h5>{step.title}</h5>
                      <p>{step.detail}</p>
                    </div>
                  </article>
                </div>
                <div className="walkthrough-controls">
                  <button type="button" onClick={() => moveStep(-1)} aria-label="Previous step">←</button>
                  <div className="walkthrough-dots" role="group" aria-label="Walkthrough steps">
                    {steps.map(({ title }, index) => (
                      <button
                        key={title}
                        type="button"
                        aria-label={`Go to step ${index + 1}: ${title}`}
                        aria-current={index === stepIndex ? "step" : undefined}
                        onClick={() => setStepIndex(index)}
                      ><span /></button>
                    ))}
                  </div>
                  <button type="button" onClick={() => moveStep(1)} aria-label="Next step">→</button>
                </div>
              </>
            )}
          </div>
        ))}
      </div>
    </section>
  );
}
